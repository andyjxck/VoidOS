const uint8_t *font_glyph(char c)
{
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    if (c < 32 || c > 90)
        c = '?';
    return glyphs[(int)c - 32];
}

int font_text_width(const char *s, int scale)
{
    int n = 0;
    while (s[n])
        n++;
    return n * 6 * scale - scale;
}

void font_draw_text(int x, int y, const char *s, uint16_t color, int scale)
{
    int cx = x;
    while (*s) {
        const uint8_t *g = font_glyph(*s++);
        for (int row = 0; row < 7; row++) {
            for (int col = 0; col < 5; col++) {
                if (g[row] & (0b10000 >> col))
                    hal_draw_rect(cx + col * scale, y + row * scale,
                                  scale, scale, color);
            }
        }
        cx += 6 * scale;
    }
}
